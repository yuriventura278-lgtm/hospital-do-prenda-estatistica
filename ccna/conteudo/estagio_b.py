def _variar_posicao_correta(estagios: dict) -> None:
    """Distribui a opção correta das perguntas de escolha múltipla pelas posições 0–3
    (de forma determinística), para a resposta certa não estar quase sempre no mesmo lugar."""
    n = 0
    for est in estagios.values():
        for t in est["tarefas"]:
            q = t["pergunta"]
            if q["tipo"] != "mc":
                continue
            alvo = n % len(q["opcoes"])
            n += 1
            c = q["correta"]
            if alvo != c:
                ops = q["opcoes"]
                ops[alvo], ops[c] = ops[c], ops[alvo]
                q["correta"] = alvo


_variar_posicao_correta(ESTAGIOS)
